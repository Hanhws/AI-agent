"""Claude Code 세션 파일(~/.claude/projects/<폴더>/<세션>.jsonl)을 읽어요.

VS Code 확장 · 터미널 · 데스크톱 앱의 Code 탭이 모두 이 파일에 대화를 남겨요. 읽기만 하고
Claude Code 설정은 건드리지 않아요. 파일 형식은 공식 약속이 아니라서 모르는 줄은 건너뛰어요.
"""
import json
import os
import re
import zlib
from pathlib import Path

KEY = "claude-code"
SITE = "claude-code"
NAME = "Claude Code"
WHERE = "VS Code 확장 · 터미널 · 데스크톱 앱의 Code 탭"

EDIT_TOOLS = {"Edit", "Write", "MultiEdit", "NotebookEdit"}
VIA = {"claude-vscode": "VS Code", "cli": "터미널", "claude-desktop": "데스크톱 앱"}
TITLE_KEYS = {"custom-title": "customTitle", "ai-title": "aiTitle", "summary": "summary"}
MAX_TEXT = 20000

# 사람이 친 글이 아니라 도구가 끼워 넣은 부분
_INJECTED = (
    "system-reminder", "ide_opened_file", "ide_selection", "ide_diagnostics", "task-notification",
    "local-command-caveat", "local-command-stdout", "local-command-stderr", "command-name",
    "command-message", "command-args", "bash-input", "bash-stdout", "bash-stderr", "user-prompt-submit-hook",
)
_INJECTED_RE = re.compile(r"<(%s)\b[^>]*>.*?</\1>" % "|".join(_INJECTED), re.S)
_WRAPPER_RE = re.compile(r"</?pasted_content\b[^>]*>|<artifact-content-authored-by-others\s*/>")
_NOT_A_PROMPT = (
    "[Request interrupted",
    "This session is being continued from a previous conversation",
    "Caveat: The messages below were generated by the user",
)


def root() -> Path:
    return Path(os.environ.get("GADAK_CLAUDE_PROJECTS", Path.home() / ".claude" / "projects")).expanduser()


def session_files() -> list:
    base = root()
    return sorted(base.glob("*/*.jsonl")) if base.is_dir() else []


def chat_id(path) -> str:
    return Path(path).stem


def new_state() -> dict:
    # open: 답을 받고 있는 질문 · answered: 그 질문에 답이나 파일 수정이 왔는지 · last: 그 질문 글의 지문
    return {"open": None, "answered": False, "last": None, "refs": [], "cwd": None, "via": None,
            "started": None, "title": None, "custom": False}


def clean_prompt(content):
    """사람이 친 글만 남겨요. 사람이 보낸 메시지가 아니면 None."""
    if isinstance(content, str):
        texts, attached = [content], 0
    elif isinstance(content, list):
        blocks = [b for b in content if isinstance(b, dict)]
        if any(b.get("type") == "tool_result" for b in blocks):
            return None
        texts = [b.get("text") or "" for b in blocks if b.get("type") == "text"]
        attached = sum(1 for b in blocks if b.get("type") in ("image", "document"))
    else:
        return None
    kept = (_WRAPPER_RE.sub("", _INJECTED_RE.sub("", text)).strip() for text in texts)
    text = "\n".join(t for t in kept if t)
    if text.startswith(_NOT_A_PROMPT):
        return None
    if not text:
        return f"(첨부 {attached}개)" if attached else None
    return text[:MAX_TEXT]


def _is_human(line) -> bool:
    if line.get("isMeta") or line.get("isSidechain") or line.get("isCompactSummary"):
        return False
    if line.get("isVisibleInTranscriptOnly") or line.get("sourceToolUseID") or "toolUseResult" in line:
        return False
    if line.get("turnOrigin") == "sdk":
        return False   # 프로그램이 보낸 질문 (예: 데스크톱 앱이 대화를 압축할 때 여는 요약 세션의 ‘Below is a conversation log…’)
    origin = line.get("origin")
    return not (isinstance(origin, dict) and origin.get("kind") not in (None, "human"))


def _clip(text):
    if isinstance(text, str) and len(text) > MAX_TEXT:
        return text[:MAX_TEXT] + "\n…(잘림)"
    return text


def _edits(tool, args) -> list:
    file = args.get("file_path") or args.get("notebook_path")
    if tool == "MultiEdit":
        pairs = [(e.get("old_string"), e.get("new_string")) for e in args.get("edits") or []]
    elif tool == "Write":
        pairs = [(None, args.get("content"))]
    elif tool == "NotebookEdit":
        pairs = [(None, args.get("new_source"))]
    else:
        pairs = [(args.get("old_string"), args.get("new_string"))]
    return [{"file": file, "old": _clip(old), "new": _clip(new)} for old, new in pairs if file]


def parse(lines, state) -> list:
    """새로 읽은 줄들을 할 일 목록으로 바꿔요. state는 이어 읽을 때 그대로 다시 넘겨요.

    돌려주는 것: ("title", 제목) · ("prompt", ref, 글, 시각) · ("more", ref, 글)
    · ("answer", ref, 글) · ("edits", ref, [변경]) · ("done", ref)
    대화가 어느 폴더에서 언제 시작됐는지는 state의 cwd · via · started에 남겨요.
    """
    ops = []
    for raw in lines:
        # 도구 결과 줄이 파일 크기의 대부분이에요. 읽을 것이 없으니 풀지 않고 넘겨요
        if '"toolUseResult":' in raw:
            continue
        try:
            line = json.loads(raw)
        except ValueError:
            continue
        if not isinstance(line, dict):
            continue
        kind = line.get("type")
        if kind in TITLE_KEYS:
            title = line.get(TITLE_KEYS[kind])
            custom = kind == "custom-title"
            if isinstance(title, str) and title.strip() and (custom or not state["custom"]):
                state["custom"] = state["custom"] or custom
                if title.strip() != state["title"]:
                    state["title"] = title.strip()
                    ops.append(("title", state["title"]))
        elif kind == "user":
            if not state["cwd"] and line.get("cwd"):
                state.update(cwd=line["cwd"], via=VIA.get(line.get("entrypoint")), started=line.get("timestamp"))
            if not _is_human(line):
                continue
            text = clean_prompt((line.get("message") or {}).get("content"))
            if text is None:
                continue
            # promptId는 hook이 넘기는 prompt_id와 같은 자리예요. 한 번 쓴 값이 또 오면 줄 id로 구분해요
            ref = line.get("promptId")
            if not ref or ref in state["refs"]:
                ref = line.get("uuid")
            if not ref or ref in state["refs"]:
                continue
            state["refs"].append(ref)
            mark = zlib.crc32(text.encode("utf-8"))
            if state["open"] and not state["answered"]:
                # 답이 오기 전에 이어서 보낸 말(또는 오류 뒤 다시 보낸 같은 말)은 앞 질문에 붙여요
                if mark != state["last"]:
                    ops.append(("more", state["open"], text))
                state["last"] = mark
                continue
            state.update(open=ref, answered=False, last=mark)
            ops.append(("prompt", ref, text, line.get("timestamp")))
        elif kind == "assistant":
            message = line.get("message") or {}
            if not state["open"] or line.get("isSidechain") or line.get("isApiErrorMessage"):
                continue
            if message.get("model") == "<synthetic>":
                continue
            texts, edits = [], []
            for block in message.get("content") or []:
                if not isinstance(block, dict):
                    continue
                if block.get("type") == "text" and (block.get("text") or "").strip():
                    texts.append(block["text"].strip())
                elif block.get("type") == "tool_use" and block.get("name") in EDIT_TOOLS:
                    edits.extend(_edits(block["name"], block.get("input") or {}))
            if texts:
                ops.append(("answer", state["open"], "\n\n".join(texts)))
            if edits:
                ops.append(("edits", state["open"], edits))
            state["answered"] = state["answered"] or bool(texts or edits)
            if message.get("stop_reason") == "end_turn":
                ops.append(("done", state["open"]))
    return ops


